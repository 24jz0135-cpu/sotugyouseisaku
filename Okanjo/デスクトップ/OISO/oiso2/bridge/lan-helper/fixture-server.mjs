import os from 'node:os';
import {start} from './server.mjs';
import QRCode from 'qrcode';
let qrContents;
const encode=QRCode.toDataURL;
QRCode.toDataURL=async function(text,...args){qrContents=JSON.parse(text);return encode.call(this,text,...args);};
const app=await start({directory:process.argv[2],port:0,adminPort:0,discoveryPort:0,quiet:true});
const address=Object.values(os.networkInterfaces()).flat().find(a=>a.family==='IPv4'&&!a.internal&&/^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.)/.test(a.address));
const response=await fetch(`http://127.0.0.1:${app.adminServer.address().port}/api/pair`,{method:'POST',headers:{'Content-Type':'application/json','X-Oaiso-Admin':'1'},body:JSON.stringify({host:address?.address})});
if(!response.ok)throw new Error('Test QR creation failed');
await response.json();
console.log(JSON.stringify(qrContents));
